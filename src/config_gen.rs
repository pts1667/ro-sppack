//! Generates the server configuration and the browser client override file.

use crate::settings::Settings;

use serde_json::{Value, json};

/// Regenerate every file the launcher owns. Safe to call before each launch.
pub fn generate_all(settings: &Settings) -> Result<String, String> {
    generate_server(settings)?;
    generate_client(settings)?;
    Ok(format!(
        "configuration written: {}, {}, {}",
        settings.server_config_json().display(),
        settings.config_local_js().display(),
        settings.webroot().join(".env").display()
    ))
}

/// Writes only `rust-ro/config.json`.
pub fn generate_server(settings: &Settings) -> Result<(), String> {
    create_directories(settings)?;
    generate_server_config(settings)
}

/// Writes only the client override and the remote client `.env`.
pub fn generate_client(settings: &Settings) -> Result<(), String> {
    create_directories(settings)?;
    generate_client_config(settings)?;
    write_remote_client_env(settings)
}

fn create_directories(settings: &Settings) -> Result<(), String> {
    for dir in [
        settings.webroot(),
        settings.resources_dir(),
        settings.server_dir(),
    ] {
        std::fs::create_dir_all(&dir).map_err(|e| format!("create {}: {e}", dir.display()))?;
    }
    Ok(())
}

fn generate_server_config(settings: &Settings) -> Result<(), String> {
    let template_path = settings.server_dir().join("config.template.json");
    let text = std::fs::read_to_string(&template_path)
        .map_err(|e| format!("read {} (is rust-ro cloned?): {e}", template_path.display()))?;
    let mut config: Value = serde_json::from_str(&text)
        .map_err(|e| format!("parse {}: {e}", template_path.display()))?;

    let server = config
        .get_mut("server")
        .ok_or_else(|| "config.template.json has no `server` section".to_string())?;
    server["host"] = json!(settings.server_host);
    server["port"] = json!(settings.game_port);
    server["packetver"] = json!(settings.packetver);
    server["enable_websocket"] = json!(true);
    // Only needed when proxying real TCP clients to rAthena/Hercules.
    server["enable_legacy_proxy"] = json!(false);
    server["enable_visual_debugger"] = json!(false);

    match server
        .get_mut("accounts")
        .and_then(|value| value.as_array_mut())
    {
        Some(accounts) => {
            if !accounts
                .iter()
                .any(|value| value.as_u64() == Some(2_000_000))
            {
                accounts.push(json!(2_000_000));
            }
        }
        None => server["accounts"] = json!([2_000_000]),
    }

    if config.get("game").is_some() {
        config["game"]["base_exp_rate"] = json!(settings.base_exp_rate);
        config["game"]["job_exp_rate"] = json!(settings.job_exp_rate);
        config["game"]["drop_rate"] = json!(settings.drop_rate);
        config["game"]["drop_rate_card"] = json!(settings.drop_rate_card);
        config["game"]["mob_density"] = json!(settings.mob_density);
    }

    let config_path = settings.server_config_json();
    let pretty =
        serde_json::to_string_pretty(&config).map_err(|e| format!("serialize config: {e}"))?;
    std::fs::write(&config_path, pretty)
        .map_err(|e| format!("write {}: {e}", config_path.display()))
}

fn generate_client_config(settings: &Settings) -> Result<(), String> {
    let path = settings.config_local_js();
    let host = settings.connect_host();
    let game_port = settings.game_port;
    let web_port = settings.web_port;
    let packetver = settings.packetver;
    let skip_intro = settings.skip_intro;

    let script = format!(
        r#"// Generated by ro-sppack. Any manual edit is overwritten on the next launch.
window.ROConfigLocal = {{
  remoteClient: 'http://{host}:{web_port}/',
  servers: [
    {{
      display: 'ro-sppack (local)',
      desc: 'Local rust-ro server',
      address: '{host}',
      port: {game_port},
      version: 25,
      langtype: 12,
      packetver: {packetver},
      renewal: false,
      worldMapSettings: {{ episode: 12 }},
      packetKeys: false,
      // rust-ro speaks WebSocket on the game port directly, so the browser
      // connects straight to it instead of a wsProxy relay.
      socketProxy: 'ws://{host}:{game_port}',
      remoteClient: 'http://{host}:{web_port}/',
      adminList: [2000000]
    }}
  ],
  skipServerList: true,
  skipIntro: {skip_intro},
  packetDump: false,
  enableMapName: true,
  enableDmgSuffix: true,
  BGMFileExtension: ['mp3'],
  saveFiles: true
}};
"#
    );

    std::fs::write(&path, script).map_err(|e| format!("write {}: {e}", path.display()))
}

/// Environment passed to the remote client process. Also written to
/// `webroot/.env` so the binary can be started by hand for testing.
fn write_remote_client_env(settings: &Settings) -> Result<(), String> {
    let mut lines = vec![
        "# Generated by ro-sppack.".to_string(),
        format!("SERVER_ROOT={}", settings.webroot().display()),
        format!("HOST={}", settings.web_bind_host()),
        format!("PORT={}", settings.web_port),
        format!(
            "CLIENT_PUBLIC_URL=http://{}:{}/",
            settings.connect_host(),
            settings.web_port
        ),
        format!("ROBROWSER_PATH={}", settings.client_dist().display()),
        "ENABLE_STATIC_SERVE=true".to_string(),
        "# rust-ro accepts WebSocket clients directly; no wsProxy relay needed.".to_string(),
        "ENABLE_WSPROXY=false".to_string(),
        "NODE_ENV=production".to_string(),
        "CLIENT_RESPATH=resources/".to_string(),
        "CLIENT_DATAINI=DATA.INI".to_string(),
        "CLIENT_AUTOEXTRACT=true".to_string(),
        "ENABLE_COMPRESSION=true".to_string(),
    ];
    for (key, value) in auxiliary_env(settings) {
        lines.push(format!("{key}={value}"));
    }
    let path = settings.webroot().join(".env");
    std::fs::write(&path, lines.join("\n") + "\n")
        .map_err(|e| format!("write {}: {e}", path.display()))
}

/// `BGM_PATH` / `AI_PATH` / `DATA_OVERRIDE_PATH` fall back to the original
/// assets folder when those files were not copied into the package.
pub fn auxiliary_env(settings: &Settings) -> Vec<(String, String)> {
    let mut env = Vec::new();
    if !settings.copy_bgm_ai {
        let bgm = settings.assets_dir.join("BGM");
        if bgm.is_dir() {
            env.push(("BGM_PATH".to_string(), bgm.display().to_string()));
        }
        let ai = settings.assets_dir.join("AI");
        if ai.is_dir() {
            env.push(("AI_PATH".to_string(), ai.display().to_string()));
        }
    }
    if !settings.copy_loose_data {
        let data = settings.assets_dir.join("data");
        if data.is_dir() {
            env.push(("DATA_OVERRIDE_PATH".to_string(), data.display().to_string()));
        }
    }
    env
}

/// Environment variables for spawning the remote client.
pub fn remote_client_env(settings: &Settings) -> Vec<(String, String)> {
    let mut env = vec![
        (
            "SERVER_ROOT".to_string(),
            settings.webroot().display().to_string(),
        ),
        ("HOST".to_string(), settings.web_bind_host()),
        ("PORT".to_string(), settings.web_port.to_string()),
        (
            "CLIENT_PUBLIC_URL".to_string(),
            format!("http://{}:{}/", settings.connect_host(), settings.web_port),
        ),
        (
            "ROBROWSER_PATH".to_string(),
            settings.client_dist().display().to_string(),
        ),
        ("ENABLE_STATIC_SERVE".to_string(), "true".to_string()),
        ("ENABLE_WSPROXY".to_string(), "false".to_string()),
        ("NODE_ENV".to_string(), "production".to_string()),
        ("CLIENT_RESPATH".to_string(), "resources/".to_string()),
        ("CLIENT_DATAINI".to_string(), "DATA.INI".to_string()),
        ("CLIENT_AUTOEXTRACT".to_string(), "true".to_string()),
        ("ENABLE_COMPRESSION".to_string(), "true".to_string()),
    ];
    env.extend(auxiliary_env(settings));
    env
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_dir(label: &str) -> std::path::PathBuf {
        let unique = std::time::SystemTime::now()
            .duration_since(std::time::SystemTime::UNIX_EPOCH)
            .map(|duration| duration.as_nanos())
            .unwrap_or(0);
        let dir = std::env::temp_dir().join(format!("ro-sppack-config-{label}-{unique}"));
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn generates_patched_server_and_client_configs() {
        let install = temp_dir("install");
        let server = install.join("rust-ro");
        std::fs::create_dir_all(&server).unwrap();
        std::fs::write(
            server.join("config.template.json"),
            r#"{
                "server": {
                    "accounts": [],
                    "host": "0.0.0.0",
                    "port": 6901,
                    "packetver": 20120229,
                    "enable_legacy_proxy": true,
                    "enable_websocket": true,
                    "enable_visual_debugger": false,
                    "log_level": "info",
                    "trace_packet": false,
                    "log_level_module_override": []
                },
                "game": {
                    "base_exp_rate": 1.0,
                    "job_exp_rate": 1.0,
                    "drop_rate": 1.0,
                    "drop_rate_card": 1.0,
                    "mob_density": 1.0
                }
            }"#,
        )
        .unwrap();

        let settings = Settings {
            install_dir: install.clone(),
            assets_dir: install.join("assets"),
            server_host: "0.0.0.0".into(),
            game_port: 7001,
            web_port: 4000,
            packetver: 20120307,
            base_exp_rate: 100.0,
            ..Settings::default()
        };

        generate_all(&settings).unwrap();

        let written = std::fs::read_to_string(server.join("config.json")).unwrap();
        let config: Value = serde_json::from_str(&written).unwrap();
        assert_eq!(config["server"]["port"], json!(7001));
        assert_eq!(config["server"]["packetver"], json!(20120307));
        assert_eq!(config["server"]["enable_legacy_proxy"], json!(false));
        assert_eq!(config["server"]["enable_websocket"], json!(true));
        assert_eq!(config["server"]["accounts"][0], json!(2_000_000));
        assert_eq!(config["game"]["base_exp_rate"], json!(100.0));

        let client =
            std::fs::read_to_string(install.join("webroot").join("Config.local.js")).unwrap();
        assert!(client.contains("socketProxy: 'ws://127.0.0.1:7001'"));
        assert!(client.contains("remoteClient: 'http://127.0.0.1:4000/'"));
        assert!(client.contains("packetver: 20120307"));

        let env = std::fs::read_to_string(install.join("webroot").join(".env")).unwrap();
        assert!(env.contains("ROBROWSER_PATH="));
        assert!(env.contains("ENABLE_WSPROXY=false"));
    }
}
